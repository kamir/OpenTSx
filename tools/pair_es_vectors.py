#!/usr/bin/env python3
"""
Writes docs/datamodel-2026/testvectors/pair-es.v1.json: event synchronisation of
pair.es (EVOLUTION/TASK-015-multivariate-analysis.md, phase 1d) as the Python
reference computes it (python-package/opentsx/algorithms/event_sync.py).

Read by python-package/tests/test_event_sync.py and by
opentsx-saas-frontend/src/workbench/es.test.ts.

Usage, from the repository root, with the package installed (pip install -e python-package):
    python3 tools/pair_es_vectors.py
"""

import json
import pathlib
import re

import numpy as np

from opentsx.algorithms.event_sync import EventSynchronization, Mulberry32

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "datamodel-2026" / "testvectors" / "pair-es.v1.json"
SHUFFLES = 10
SEED = 1


def expect(es, events_a, events_b, tau_max=None):
    q, q_ab, q_ba = es.calculate_synchronization(events_a, events_b, tau_max)
    q_rand = es.surrogate_sync(events_a, events_b, SHUFFLES, SEED, tau_max)
    return {"q_total": q, "q_ab": q_ab, "q_ba": q_ba, "q_rand": q_rand}


def from_events(name, events_a, events_b, tau_max=None):
    es = EventSynchronization()
    return {
        "name": name,
        "eventsA": [int(e) for e in events_a],
        "eventsB": [int(e) for e in events_b],
        "tauMax": tau_max,
        "expect": expect(es, np.asarray(events_a), np.asarray(events_b), tau_max),
    }


def from_values(name, a, b):
    es = EventSynchronization()
    events_a = es.detect_events(a)
    events_b = es.detect_events(b)
    return {
        "name": name,
        "a": [float(v) for v in a],
        "b": [float(v) for v in b],
        "sigma": 2,
        "tauMax": None,
        "eventsA": [int(e) for e in events_a],
        "eventsB": [int(e) for e in events_b],
        "expect": expect(es, events_a, events_b),
    }


def main():
    rng = np.random.default_rng(15)
    a = rng.standard_normal(400)
    noise = rng.standard_normal(400)
    other = rng.standard_normal(400)
    short = np.array([0.0, 0.2, 0.0, 6.0, 0.0, 0.1, 0.0, 5.15, 0.0, 0.2, 0.0, 0.1])
    cases = [
        from_events("identical event lists", [3, 10, 18, 25, 40, 41, 60], [3, 10, 18, 25, 40, 41, 60]),
        from_events("B 10 ticks after A, local window", [0, 100, 200, 300], [10, 110, 210, 310]),
        from_events("B 10 ticks after A, window capped at 5", [0, 100, 200, 300], [10, 110, 210, 310], 5.0),
        from_events("irregular events, B partly after A", [2, 9, 15, 31, 47, 52, 70, 88], [4, 13, 15, 33, 60, 71, 90, 95]),
        from_values("B follows A by 2 ticks", a, np.roll(a, 2)),
        from_values("B follows A by 3 ticks, with noise", a, np.roll(a, 3) + 0.3 * noise),
        from_values("independent series", a, other),
        # the peak of 5.15 lies between mean + 2 std with the population std (5.107) and with the sample std (5.291)
        from_values("short series, a peak between the two thresholds", short, np.roll(short, 1)),
    ]
    rand1 = Mulberry32(1)
    rand42 = Mulberry32(42)
    doc = {
        "schema": "opentsx.testvectors.pair-es.v1",
        "description": (
            "Event synchronisation of pair.es after Quiroga, Kreuz and Grassberger, as "
            "python-package/opentsx/algorithms/event_sync.py computes it: events are local maxima above "
            "mean + sigma * std (population std), q_total = Q, q_ab = c(B|A) / sqrt(mA mB) (A leads), "
            "q_ba = c(A|B) / sqrt(mA mB), q_rand = mean Q of A against " + str(SHUFFLES) + " copies of B "
            "with shuffled inter-event intervals, drawn by Mulberry32(" + str(SEED) + "). Times are tick "
            "indices. Generated by tools/pair_es_vectors.py; run by python-package/tests/test_event_sync.py "
            "and opentsx-saas-frontend (es.test.ts)."
        ),
        "shuffles": SHUFFLES,
        "seed": SEED,
        "mulberry32": {"1": [rand1() for _ in range(5)], "42": [rand42() for _ in range(5)]},
        "cases": cases,
    }
    text = json.dumps(doc, indent=1)
    # a list of numbers on one line, so the file reads by case
    text = re.sub(r"\[\s*([-0-9.e, \n]+?)\s*\]", lambda m: "[" + re.sub(r"\s*\n\s*", " ", m.group(1)) + "]", text)
    OUT.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
