#!/usr/bin/env python3
"""Regenerate or verify the shared Java aggregate transport vectors."""

import argparse
import pathlib
import subprocess


ROOT = pathlib.Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated bytes with the committed file")
    args = parser.parse_args()
    command = [
        "mvn", "-B", "-ntp", "-pl", "opentsx-wayang", "-am", "test",
        "-Dtest=AggregateTransportVectorsTest", "-Dsurefire.failIfNoSpecifiedTests=false",
    ]
    if not args.check:
        command.append("-Dopentsx.aggregate.vectors.generate=true")
    subprocess.run(command, cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
