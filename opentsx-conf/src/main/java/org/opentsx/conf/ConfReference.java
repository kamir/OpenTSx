package org.opentsx.conf;

import org.opentsx.conf.Registry.Key;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Renders the configuration reference from the registry: appendix D of the user manual and the templates of the
 * defaults file in both formats. {@code ConfReference [<repository root>]} writes the three files.
 */
public final class ConfReference {

    public static final String REGISTRY = "opentsx-conf/src/main/resources/org/opentsx/conf/opentsx.config.v1.json";
    public static final String APPENDIX = "docs/user-manual/appendix-d-configuration.md";
    public static final String PROPERTIES_TEMPLATE = "conf/opentsx-defaults.conf.template";
    public static final String YAML_TEMPLATE = "conf/opentsx-defaults.yaml.template";
    public static final String REGENERATE = "java -cp \"$(bin/opentsx classpath opentsx-conf)\" org.opentsx.conf.ConfReference";

    static final String READERS = "# opentsx config show, opentsx config get and code that calls OpenTsxConf.load read this file; code,\n"
            + "# the command line, the environment and --properties-file win over it. The other commands of bin/opentsx\n"
            + "# parse their own flags and do not read it.\n";
    static final Pattern MARKDOWN_SPECIAL = Pattern.compile("([\\\\`*_\\[\\]<>|])");
    static final Pattern PLAIN_YAML = Pattern.compile("^[A-Za-z0-9./][A-Za-z0-9._/:-]*$");

    private ConfReference() {
    }

    public static void main(String[] args) {
        if (args.length > 1) {
            System.err.println("opentsx: " + args[1] + ": unexpected argument; expected ConfReference [<repository root>]");
            System.exit(2);
        }
        Path root = Path.of(args.length == 1 ? args[0] : ".").toAbsolutePath().normalize();
        try {
            for (String f : write(root)) {
                System.out.println("wrote " + f);
            }
        } catch (NoSuchFileException e) {
            System.err.println("opentsx: " + e.getFile() + ": no such file; run ConfReference from the repository root or give the root");
            System.exit(2);
        } catch (IOException | RuntimeException e) {
            System.err.println("opentsx: " + e.getMessage());
            System.exit(1);
        }
    }

    static List<String> write(Path root) throws IOException {
        Registry registry = Registry.parse(Files.readAllBytes(root.resolve(REGISTRY)));
        List<String> written = new ArrayList<>();
        for (Map.Entry<String, String> f : render(registry, ConfCli.version()).entrySet()) {
            Path p = root.resolve(f.getKey());
            Files.createDirectories(p.getParent());
            Files.writeString(p, f.getValue(), StandardCharsets.UTF_8);
            written.add(f.getKey());
        }
        return written;
    }

    public static Map<String, String> render(Registry registry, String version) {
        Map<String, String> out = new LinkedHashMap<>();
        out.put(APPENDIX, appendix(registry, version));
        out.put(PROPERTIES_TEMPLATE, propertiesTemplate(registry, version));
        out.put(YAML_TEMPLATE, yamlTemplate(registry, version));
        return out;
    }

    static String appendix(Registry registry, String version) {
        Map<String, List<Key>> areas = areas(registry);
        StringBuilder sb = new StringBuilder();
        sb.append("<!-- Generated by org.opentsx.conf.ConfReference from ").append(REGISTRY).append(". Do not edit. -->\n");
        sb.append("# Appendix D: Configuration keys\n\n");
        sb.append("This appendix lists every key of the registry `opentsx.config.v1` at project version ").append(version)
                .append(", keys marked `unreleased` included: ").append(registry.keys().size()).append(" keys in ")
                .append(areas.size()).append(" areas.\n\n");
        sb.append("[Chapter 18](18-configuration.md) shows how to set a key and which source wins. This page and the templates\n")
                .append("[`opentsx-defaults.conf.template`](../../conf/opentsx-defaults.conf.template) and\n")
                .append("[`opentsx-defaults.yaml.template`](../../conf/opentsx-defaults.yaml.template) are generated from\n")
                .append("[`opentsx.config.v1.json`](../../opentsx-conf/src/main/resources/org/opentsx/conf/opentsx.config.v1.json).\n")
                .append("Regenerate them from the repository root:\n\n");
        sb.append("```bash\n").append(REGENERATE).append("\n```\n\n");
        sb.append("## Read the tables\n\n");
        sb.append("| Column | Content |\n|---|---|\n");
        sb.append("| Key | the key; `--conf <key>=<value>`, a properties or YAML file and `set` in code take it |\n");
        sb.append("| Type | the type of the value; `one of` lists the values of an enum, `unit` names the unit of a bare number |\n");
        sb.append("| Default | the registry default; none means the key has no value until a source sets it |\n");
        sb.append("| Alias | the flags that set the key on the command line of a command that reads it |\n");
        sb.append("| Env | the environment variables: the canonical name first, then the legacy names |\n");
        sb.append("| Meaning | what the key sets |\n");
        sb.append("| Since | the first OpenTSx release that reads the setting under any name; `unreleased` means no release reads it yet |\n\n");
        sb.append("The Env column, `--conf`, `--properties-file` and the defaults file reach `opentsx config show`,\n")
                .append("`opentsx config get` and code that calls `OpenTsxConf.load`. The other commands of `bin/opentsx` parse their\n")
                .append("own flags and do not read them; see [chapter 18](18-configuration.md).\n\n");
        sb.append("A key marked **Secret.** comes only from code, the environment or a file. `OpenTsxConf.load` refuses it on the\n")
                .append("command line, so its Alias is none. Every output of `opentsx config` shows its value as `******`. A secret has no\n")
                .append("default.\n");
        for (Map.Entry<String, List<Key>> area : areas.entrySet()) {
            sb.append("\n## ").append(area.getKey()).append("\n\n");
            sb.append("| Key | Type | Default | Alias | Env | Meaning | Since |\n|---|---|---|---|---|---|---|\n");
            for (Key e : area.getValue()) {
                List<String> type = new ArrayList<>();
                type.add(code(e.typeName()));
                if (!e.values().isEmpty()) {
                    type.add("one of " + String.join(", ", e.values().stream().map(ConfReference::code).toList()));
                }
                if (e.unit() != null) {
                    type.add("unit " + code(e.unit()));
                }
                List<String> flags = e.secret() ? List.of() : e.flags().stream().map(f -> code("--" + f)).toList();
                sb.append("| ").append(code(e.key()))
                        .append(" | ").append(String.join(", ", type))
                        .append(" | ").append(e.defaultValue() == null ? "none" : code(e.defaultValue()))
                        .append(" | ").append(flags.isEmpty() ? "none" : String.join(", ", flags))
                        .append(" | ").append(String.join(", ", e.envNames().stream().map(ConfReference::code).toList()))
                        .append(" | ").append(e.secret() ? "**Secret.** " : "").append(escape(e.doc()))
                        .append(" | ").append(e.since())
                        .append(" |\n");
            }
        }
        return sb.toString();
    }

    static String propertiesTemplate(Registry registry, String version) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Defaults file in the properties format, with every key of the registry opentsx.config.v1 at project\n")
                .append("# version ").append(version).append(". Generated by org.opentsx.conf.ConfReference.\n")
                .append("#\n")
                .append("# Copy this file to $OPENTSX_CONF_DIR/opentsx-defaults.conf. To set a key, remove the \"# \" in front of it and\n")
                .append("# write its value after the key; a key without default has no value yet. A line is \"key value\" or\n")
                .append("# \"key = value\"; a line that starts with # or ! is a comment; a backslash is an error. A # after\n")
                .append("# the key is part of the value.\n")
                .append(READERS);
        for (Key e : registry.keys()) {
            sb.append("\n# ").append(e.doc()).append('\n');
            sb.append("# ").append(plainType(e)).append('\n');
            sb.append("# ").append(e.key());
            if (e.defaultValue() != null) {
                sb.append(' ').append(e.defaultValue());
            }
            sb.append('\n');
        }
        return sb.toString();
    }

    static String yamlTemplate(Registry registry, String version) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Defaults file in YAML, with every key of the registry opentsx.config.v1 at project version ").append(version)
                .append(".\n# Generated by org.opentsx.conf.ConfReference.\n")
                .append("#\n")
                .append("# Copy this file to $OPENTSX_CONF_DIR/opentsx-defaults.yaml. To set a key, remove the \"# \" in front of it and\n")
                .append("# in front of the maps above it, and write its value after the colon; a key without default has no value yet.\n")
                .append("# Python reads YAML only with the extra opentsx[yaml].\n")
                .append(READERS)
                .append("#\n");
        List<String> previous = List.of();
        for (Key e : registry.keys()) {
            List<String> segments = List.of(e.key().split("\\."));
            int common = 0;
            while (common < segments.size() - 1 && common < previous.size() - 1
                    && segments.get(common).equals(previous.get(common))) {
                common++;
            }
            for (int i = common; i < segments.size() - 1; i++) {
                sb.append("# ").append("  ".repeat(i)).append(segments.get(i)).append(":\n");
            }
            String indent = "  ".repeat(segments.size() - 1);
            sb.append("# ").append(indent).append("# ").append(e.doc()).append('\n');
            sb.append("# ").append(indent).append("# ").append(plainType(e)).append('\n');
            sb.append("# ").append(indent).append(segments.get(segments.size() - 1)).append(':');
            if (e.defaultValue() != null) {
                sb.append(' ').append("list".equals(e.type()) ? yamlList(e.defaultValue()) : yamlScalar(e.defaultValue()));
            }
            sb.append('\n');
            previous = segments;
        }
        return sb.toString();
    }

    static Map<String, List<Key>> areas(Registry registry) {
        Map<String, List<Key>> out = new LinkedHashMap<>();
        for (Key e : registry.keys()) {
            out.computeIfAbsent("opentsx." + e.key().split("\\.")[1], a -> new ArrayList<>()).add(e);
        }
        return out;
    }

    static String plainType(Key e) {
        StringBuilder sb = new StringBuilder("Type: ").append(e.typeName());
        if (!e.values().isEmpty()) {
            sb.append(", one of ").append(String.join(", ", e.values()));
        }
        if (e.unit() != null) {
            sb.append(", unit ").append(e.unit());
        }
        if (e.secret()) {
            sb.append("; secret: environment or file only");
        }
        if (e.defaultValue() == null) {
            sb.append("; no default");
        }
        return sb.append('.').toString();
    }

    static String yamlList(String value) {
        return "[" + String.join(", ", List.of(value.split(",")).stream().map(ConfReference::yamlScalar).toList()) + "]";
    }

    static String yamlScalar(String value) {
        if (PLAIN_YAML.matcher(value).matches() && !ConfParser.YAML_NULLS.contains(value)) {
            return value;
        }
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }

    static String code(String s) {
        return "`" + s.replace("|", "\\|") + "`";
    }

    static String escape(String s) {
        return MARKDOWN_SPECIAL.matcher(s).replaceAll("\\\\$1");
    }
}
