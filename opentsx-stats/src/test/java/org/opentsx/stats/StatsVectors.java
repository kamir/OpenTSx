package org.opentsx.stats;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.opentsx.model.Micros;
import org.opentsx.model.v2.SeriesStats;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HexFormat;

final class StatsVectors {

    static final ObjectMapper JSON = new ObjectMapper();
    static final Path DIRECTORY = Path.of("..", "docs", "datamodel-2026", "testvectors");

    private StatsVectors() {
    }

    static ObjectNode document(String name, String description) {
        ObjectNode doc = JSON.createObjectNode();
        doc.put("schema", "opentsx.testvectors." + name + ".v1");
        doc.put("description", description + " Generated by tools/java_operator_vectors.py. "
                + "Non-finite doubles are strings: NaN, Infinity and -Infinity. Timestamps are epoch microseconds.");
        doc.putArray("cases");
        return doc;
    }

    static void write(String name, ObjectNode doc) throws IOException {
        Files.writeString(DIRECTORY.resolve(name + ".v1.json"),
                JSON.writerWithDefaultPrettyPrinter().writeValueAsString(doc) + "\n");
    }

    static JsonNode read(String name) throws IOException {
        return JSON.readTree(DIRECTORY.resolve(name + ".v1.json").toFile());
    }

    static double number(JsonNode value) {
        return value.isTextual() ? Double.parseDouble(value.textValue()) : value.doubleValue();
    }

    static void put(ObjectNode node, String key, double value) {
        if (Double.isFinite(value)) {
            node.put(key, value);
        } else {
            node.put(key, Double.toString(value));
        }
    }

    static ArrayNode values(double... values) {
        ArrayNode out = JSON.createArrayNode();
        for (double value : values) {
            if (Double.isFinite(value)) {
                out.add(value);
            } else {
                out.add(Double.toString(value));
            }
        }
        return out;
    }

    static ObjectNode stats(SeriesStats s) {
        ObjectNode out = JSON.createObjectNode();
        out.put("seriesId", s.getSeriesId());
        out.put("windowType", s.getWindowType());
        out.put("windowStartMicros", Micros.of(s.getWindowStart()));
        out.put("windowEndMicros", Micros.of(s.getWindowEnd()));
        out.put("validCount", s.getValidCount());
        out.put("nanCount", s.getNanCount());
        out.put("gapCount", s.getGapCount());
        put(out, "min", s.getMin());
        put(out, "max", s.getMax());
        put(out, "mean", s.getMean());
        put(out, "m2", s.getM2());
        if (s.getLastSeen() == null) {
            out.putNull("lastSeenMicros");
        } else {
            out.put("lastSeenMicros", Micros.of(s.getLastSeen()));
        }
        if (s.getQuantileSketch() == null) {
            out.putNull("sketchHex");
        } else {
            ByteBuffer buffer = s.getQuantileSketch().duplicate();
            byte[] bytes = new byte[buffer.remaining()];
            buffer.get(bytes);
            out.put("sketchHex", HexFormat.of().formatHex(bytes));
            ArrayNode quantiles = out.putArray("quantiles");
            QuantileSketch sketch = QuantileSketch.fromBytes(bytes);
            for (double q : new double[]{0.01, 0.5, 0.99}) {
                ObjectNode point = quantiles.addObject();
                point.put("q", q);
                put(point, "value", sketch.quantile(q));
            }
        }
        return out;
    }
}
